#!/usr/bin/env bash
#  ⭐ DEVLOOP-GATES-REV: 9
#  ⭐ DEVLOOP-PREFLIGHT: 1   ← 声明「我支持开跑前验判据」（G-127）
#     ⛔ 这一行是给工具看的**声明**，不是注释：`devloop/gates.py::preflight`
#     先读它，没有就**一行都不跑**（否则不认识开关的老闸会照常跑全套几十分钟，
#     ⚠️ 实测第一版就是这么挂了 5 分钟的）。
#     ⛔ **改本模板时必须把这个数加一**，并把这一行原样留在你项目的副本里。
#     ⚠️ 它是 `devloop doctor` 用来发现「装出去的那份过期了」的唯一线索。
#     G-114：G-88 的修法进了模板，而 eco-ob 装的那份从来没跟上，
#     同一个假绿多活了三天，且**没有任何东西会告诉你**。
# ══════════════════════════════════════════════════════════════
#  <项目名> · 验收闸
# ══════════════════════════════════════════════════════════════
#
#  ⭐ 这个文件回答一个问题：**「这单活干完了吗」——由脚本裁决，不由模型自述。**
#
#  用法：复制到 <项目>/.devloop/gates.sh → 把每个 <...> 换成你的内容 →
#        删掉所有「模板说明」注释块 → `devloop gates --project <路径>` 试跑。
#
# ── 协议（工具只认这四样，⛔ 不许自创）─────────────────────────
#
#  输出：每道闸一行，制表符分隔
#      PASS<TAB>闸名<TAB>说明     验过，且过了
#      FAIL<TAB>闸名<TAB>说明     验过，没过
#      SKIP<TAB>闸名<TAB>说明     本来能验，**这次被开关跳过了**
#      VOID<TAB>闸名<TAB>说明     ⛔ **我这一道本来就没有可验的东西**
#
#  ⭐ SKIP 与 VOID 对「能不能放行」含义相同（都不算通过），
#     但对**排查**含义完全不同：SKIP 要去查谁把开关打开了，
#     VOID 要去查为什么这个项目里它是空的。⛔ 所以必须分成两档。
#
#  ⚠️ **VOID 的判据只能在闸自己身上**——只有它知道有没有东西可验。
#     外面用启发式（「说明里没数字就算空过」）会误伤真验过的那些。
#
#  退出码：
#      0 = 全都验过且都过了
#      1 = 有闸没过（**活没干好**）
#      2 = 闸自己坏了（**先修环境，不是活的问题**）
#
#  ⛔ 这三个码必须分清。1 和 2 混在一起，环境故障会被当成质量问题，
#     而那会让人去改代码解决一个跟代码无关的问题。
#  ⚠️ 协议外的退出码（脚本语法错、set -u 撞未赋值变量的 127、被信号杀死的
#     128+N）**工具一律归一化成 2**——「我不认识这个结果」本身就是闸故障。
#
# ── ⛔ 四条会让这份闸变成摆设的写法（本项目全部实测栽过）────────
#
#  1. **退出 0 但一道 PASS 都没有。**
#     工具会把它判成「闸自身故障」而不是绿——因为退出 0 的含义是
#     「全都验过且都过了」，而一道都没验的时候那句话是假的。
#     ⚠️ 所以：**每条能过的路径都要 `pass`**，不要只在失败时才输出。
#
#  2. **`cmd | head; echo $?` 取到的是 head 的退出码。**
#     永远是 0。判断上游命令的成败必须直接取，不许从管道后面取。
#
#  3. **`set -u` 撞未赋值变量 → 127，而且往往只在失败路径上才撞到。**
#     实测过一次：某个变量只在「测试失败」的分支里被引用，
#     于是绿的时候一切正常、真出问题的那天闸自己先炸了。
#     ⚠️ **修复本身也要红测**——把它弄红一次，看闸是不是真的报红。
#
#  4. ⭐⭐ **判「退出码是不是 0」。**（2026-08-12 加，⛔ 这条最贵）
#
#     ⛔ **在任何有历史红的仓库上，这个判据对任何工人都必然红。**
#     闸这时测的不是工人，是「这个仓库里有没有红」——而那跟这一单干得好不好无关。
#
#     ⚠️ 实测账单：靶子项目连败 4 单，其中 **3 单**栽在这上面。
#     铁证是 2026-08-05 那一单：工人**一个文件都没动**，闸照样红
#     （`✗ M1 回归: 退出码 1，通过 37 失败 1`）。
#     ⭐ 而写那份计划的人**已经识别出**这道闸「必红且没有信息量」，
#     以为不点名（不写进 `require_pass`）就排除掉了 —— ⛔ **代码里排除不掉**：
#     任何一道 `bad()` 都置 `fail=1`，脚本末尾 `exit $fail`，整份闸就红了。
#
#     ⭐⭐ **所以写完闸的第一件事是「绿检」：**
#         ```
#         devloop gates --project <项目> --commit HEAD     # 工人零改动
#         ```
#         **退出码必须是 0、FAIL 必须是 0 行。**
#         ⛔ 不是 0 = 这道闸测的不是工人，先修闸再谈派单。
#
#     ⚠️ 「绿检」这条纪律在 `templates/task.md` 里写了 5 遍
#     （教给了**写作业的人**），⛔ 而在本文件里 2026-08-12 之前是 **0 遍**
#     （没教给**写闸的人**）—— 而 4 单里 3 单死在闸上，不是死在作业上。
#     ⭐ 又一次「同一件事有两条路，修好的永远是有人盯着的那条」。
#
# ══════════════════════════════════════════════════════════════
#  ⭐⭐ 闸的三种形状（⛔ 别只会写第二种）
# ══════════════════════════════════════════════════════════════
#
#  **形状一 · 改动守卫** —— 判「工人有没有碰不该碰的东西」。
#     纯 `git status` / `git diff`，不跑被测代码。⚠️ 便宜，但**一行业务代码都不验**。
#
#  **形状二 · 基线对照闸** —— 判「**失败条目有没有变多**」，⛔ 不判「红不红」。
#     ⭐ 这是形状二的正确写法；「判退出码」是它的错误写法（见上面第 4 条）。
#     做法：
#       ① 跑测试，把 `^FAIL` 行**折成名字**（抹掉所有数字，压空白，排序）；
#       ② 与**入库的改前红榜**用同一套折法算出的集合逐条比；
#       ③ **新增 ≥1 条 → FAIL 并点名**；没有新增 → PASS。
#       ④ 「消失的失败」只报 ⚠️ 不判红（顺手修好别人的红也是世界变了，请人看一眼）。
#     ⚠️ 为什么折成名字：数字每次都会变（浮点、耗时、计数），⛔ 名字不会。
#     实测：同一条断言在两份存档里数字是 588081228120 / 594934026897，
#     ⭐ 折成名字之后**逐字相同**。
#     ⛔ **别拿整行文本比**：工人真把那条红修绿了，行首从 FAIL 变 PASS、
#        文本必然不等 ⇒ **干对了反而被判红**。
#     ⛔ **必须防空转**：`PASS` 和 `FAIL` 都是 0 行时（引擎没起来 / 脚本崩了），
#        「没有新增失败」这句话是**真的但毫无意义** —— 那时必须 FAIL，
#        ⚠️ 这正是七种假绿的第二种「空转即绿」。
#     ⛔ **墙钟类断言整条摘出去，只打印不判定** —— 它跑在什么机器上、
#        当时多忙都会变，拿它判工人是**假红**。
#
#  **形状三 · 正面判据闸** —— 跑被测代码，只验**这一单想立的那件事**。
#     ⭐ 为什么必须有它：形状一二回答的都是「**跟以前比变没变**」，
#     ⛔ 它们答不了「**改对了没有**」。
#     ⚠️ 实测：靶子项目某一轮七个套件全量回归**失败一条没多、还是原来那批**，
#     而代码是错的 —— 是一支正面判据探针当场喷出「已经饱着还吃进去 351 次」。
#     ⛔ 挑探针进闸时先查一件事：**它会不会真的红？**
#     实测有两支的主流程以**无条件 `quit(0)`** 结尾（非零只用于「配置无效」）
#     ⇒ 世界怎么变都返回 0，装进闸就是「守卫的目标不存在」。
#
# ══════════════════════════════════════════════════════════════

set -uo pipefail
# ⚠️ 不加 `-e`：闸要**跑完所有检查再汇总**，中途 exit 会漏掉后面几道。

WORK="${1:-$(pwd)}"      # 工具传进来的检查目标（干净检出的 worktree 或工作区）
fail=0

pass() { printf 'PASS\t%s\t%s\n' "$1" "$2"; }
bad()  { printf 'FAIL\t%s\t%s\n' "$1" "$2"; fail=1; }
skip() { printf 'SKIP\t%s\t%s\n' "$1" "$2"; }
#  ⛔ `void` 与 `skip` 一样**不置 `fail=1`**：「没有可验之物」不是错误。
#     ⚠️ 要不要因此拦住，由计划里的 `require_pass` 决定——点名了就落退出码 2 交人。
#  ⭐ 手边没有这个函数的人，最省力的写法就是 `pass`——而那正是 G-68 的成因。
void() { printf 'VOID\t%s\t%s\n' "$1" "$2"; }

# ⚠️ 环境不对要**早退且退 2**，不要让后面的检查在坏环境上跑出假结论。
#
# ⛔⛔ 2026-08-16：源码目录那一条**必须排在体检之后**（它原来在这里）。
#    ⚠️ 排在前面时，源码目录不在 → 脚本掉头就走、**一个字的体检都不打**，
#    而 `gates.py::preflight` 把「一行都没有」读成 `unknown`
#    ——按契约 `unknown` 是**放行**的。⇒ **最该拦的那种坏，恰恰是唯一拦不住的。**
#    ⭐ 挪到体检之后，这种坏就由体检自己以 `pf "语法" "BAD"` 报出来。
[ -d "$WORK" ] || { echo "检查目标不存在：$WORK" >&2; exit 2; }


# ── ⭐⭐ 体检模式（DEVLOOP-PREFLIGHT: 1）─────────────────────────
#
# ⛔ 这一段存在的理由（2026-08-08，真实账单）：一道**数学上必然红**的闸
#    烧掉 **514 万 tokens**、产出 **0 个文件**，⚠️ 还把一个 **42 秒**就改对了的工人
#    逼得**删掉自己正确的代码**（它的原话：「我确认逻辑无懈可击但仍破基线，
#    说明我漏了某处副作用」），然后追了 49 分钟一个不存在的 bug。
#    ⚠️ 根因不在工人：那道闸的对照存档录于 7 个提交之前，工人做什么都过不了。
#
# ⭐ 拓扑上的洞：这个工具的防线**全在花钱之前**拦（配额、宪法、禁改清单……），
#    ⛔ 唯独「判据本身对不对」要**花完钱才知道** —— 因为它写在闸里，
#    而闸只在工人干完之后才跑。⭐ 体检模式就是把这一道也挪到花钱之前。
#    实测：同一件事从「50 分钟 + 514 万 tokens」变成 **0.55 秒**。
#
# ⭐ 契约（`devloop/gates.py::preflight` 认这个）：
#    收到 `DEVLOOP_PREFLIGHT=1` 时 ——
#    ⛔ **不许跑任何要几十分钟的大考**，只检查**自己的前提**，
#    每道闸打一行 `PREFLIGHT<TAB>闸名<TAB>OK|BAD|VOID<TAB>说明`，然后**立即退出 0**。
#
# ⚠️ 三档的含义（⛔ 别混）：
#    OK   = 我的前提在，跑起来是有意义的
#    BAD  = ⛔ 我的前提坏了，**这道闸现在必然红，跟工人干得好不好无关**
#    VOID = ⚠️ 判不了（缺信息）—— ⛔ **别读成通过**
#
# ⭐ 哪些闸**必须**在这里出现：凡是靠「**外部对照物**」判定的闸
#    （改前存档、参考基线、答案卷、金标准输出……）。
#    ⚠️ 它们是最容易腐烂的一类：代码往前走，对照物留在原地，
#    ⛔ 而腐烂**不会有任何征兆**，直到烧完钱才发现。
#    ⭐ 判据落在「这份对照物是在哪个提交上录的」vs「本单的基准提交」。
pf() { printf 'PREFLIGHT\t%s\t%s\t%s\n' "$1" "$2" "$3"; }

# ⭐⭐ 2026-08-16 加的**双向判据**（本仓实测出来的，⛔ 单向会漏掉更贵的一半）：
#
# | 方向 | 差集不空的后果 |
# |---|---|
# | **真跑有、体检没有** | ⛔ 点名它 → **还没花一分钱就被拒**（本仓实测 7 份计划拒 6 份） |
# | **体检有、真跑没有** | ⛔⛔ 点名它 → 体检**放行** → **花完钱**才收「闸与验收契约对不上」 |
#
# ⇒ **下面报出的闸名，必须与真跑时打出的判定行逐字相等。**
# ⚠️ 「真跑」指的是**干净检出**那一种（编排方一律 `clean_checkout=True`），
#    ⛔ 别按 `DEVLOOP_CLEAN_CHECKOUT` 分支 —— 体检自己天然拿不到那个标记。
# ⭐ 守卫写法见工具仓 `tests/test_preflight_roster.py`：它**真跑一次闸**再对账，
#    ⛔ 不读脚本文本 —— 本仓两个活例（`环境自检`、`改动守卫`）读脚本都读不出来。
if [ "${DEVLOOP_PREFLIGHT:-0}" = "1" ]; then
  # ── ⭐ 靠外部对照物的闸：先问「这份对照物配不配得上这份代码」──
  #    ⚠️ `DEVLOOP_BASE_COMMIT` 由 `devloop/gates.py::run_gates` 塞进环境变量，
  #    它是**本单的基准提交**。⛔ 编排方没给就只能判 VOID，别猜。
  #
  # ⛔⛔ 2026-08-16：整块**必须先问「这个项目有没有对照物存档」**。
  #    ⚠️ 以前无条件跑，于是**没有存档的项目每次都报 BAD ⇒ 永远拒单**，
  #    而它报的那个闸名在真跑里根本不存在（违反上面的双向判据第二条）。
  #    ⭐ 这是**样板**：你的项目有这类闸（改前存档 / 参考基线 / 答案卷）就照着填，
  #    没有就让这块自然跳过 —— ⛔ 别为了「看起来完整」硬留一个空壳。
  #
  # ⛔⛔ **启用这一块，就必须在下面实现一道同名的闸。**
  #    只填体检、不实现闸 = 违反上面的双向判据第二条：
  #    点名它 → 体检放行 → **花完钱**才收「闸与验收契约对不上」。
  #    ⚠️ 这一点**读脚本读不出来**（出厂状态下这块被目录检查挡着、根本不执行）
  #    —— 判它的唯一办法是**真跑一次体检 + 真跑一次闸**再对账。
  if [ -d "$WORK/<对照物存档>" ]; then
    if [ ! -f "$WORK/<对照物存档>/BASELINE_COMMIT" ]; then
      pf "<靠对照物的那道闸>" "BAD" "⛔ 存档没记它是在哪个提交上录的——无从判断它配不配得上这份代码"
    elif [ -z "${DEVLOOP_BASE_COMMIT:-}" ]; then
      pf "<靠对照物的那道闸>" "VOID" "⚠️ 编排方没给基准提交——⛔ 判不了存档新旧，别读成通过"
    else
      want=$(tr -d ' \r\n' < "$WORK/<对照物存档>/BASELINE_COMMIT")
      got="${DEVLOOP_BASE_COMMIT}"
      if [ "${want:0:12}" = "${got:0:12}" ]; then
        pf "<靠对照物的那道闸>" "OK" "存档录于 ${want:0:12}，与本单基准一致"
      else
        n=$(cd "$WORK" && git rev-list --count "$want".."$got" 2>/dev/null || echo "?")
        pf "<靠对照物的那道闸>" "BAD" "⛔ 存档录于 ${want:0:12}，而本单基准是 ${got:0:12}（隔着 $n 个提交）——这道闸**数学上必然红**，工人做什么都过不了"
      fi
    fi
  fi

  # ── ⭐ 不靠对照物的闸：只要输入在就行，但**也要报一行** ──
  #    ⛔ 不报 = 体检报告里看不见它，而「没出现」和「没问题」长得一模一样
  #    （七种假绿第一种：守卫的目标不存在）。
  #
  # ⛔⛔ 2026-08-16：这里以前只报一个占位名 `<其余点名闸>`，
  #    而本文件真跑时打出的是**五个有名有姓的**：语法 / 改动守卫 / 测试守卫 /
  #    禁改清单 / 测试。⇒ 照模板接闸的项目，把源码目录填好之后**第一次派单就被自己拒掉**，
  #    而错误里点的是它从没听说过的名字。⭐ 下面这几行请连**闸名**一起改成你项目里的真名。
  if [ ! -d "$WORK/<你的源码目录>" ]; then
    pf "语法" "BAD" "⛔ $WORK 下没有 <你的源码目录> —— 后面每一道都会在坏环境上跑出假结论"
  else
    pf "语法" "OK" "<你的源码目录>/ 在——判据全在仓内"
    #  ⚠️ 这三道只在**干净检出**里有意义，而真跑一律是干净检出。
    #  ⛔ 别按 DEVLOOP_CLEAN_CHECKOUT 分支：体检拿不到它，一分支就永远报 VOID，
    #     整份体检被拖成 unknown（= 谁也没验过）。
    pf "改动守卫" "OK" "真跑在干净检出里，这道会验"
    pf "测试守卫" "OK" "真跑在干净检出里，这道会验"
    pf "禁改清单" "OK" "真跑在干净检出里，这道会验"
    if [ -d "$WORK/<你的测试目录>" ]; then
      pf "测试" "OK" "<你的测试目录>/ 在"
    else
      pf "测试" "BAD" "⛔ 找不到 <你的测试目录>/ —— 全量测试那道闸必然验 0 条"
    fi
  fi

  exit 0
fi

# ⚠️ 早退排在体检**之后**（原因见上面那段）。
[ -d "$WORK/<你的源码目录>" ] || { echo "$WORK 下没有 <你的源码目录>" >&2; exit 2; }


# ── 闸 1 · 最便宜的检查放最前 ──────────────────────────────────
# ⚠️ 顺序有讲究：语法/编译坏了，后面跑测试都是白跑，而且报错会更难读。
if out=$(cd "$WORK" && <你的语法或编译命令> 2>&1); then
  pass "语法" "<通过时说什么>"
else
  bad "语法" "$(printf '%s' "$out" | head -1)"
fi


# ── 闸 2 · 改动守卫（⚠️ 只在干净检出里有意义）──────────────────
#
#  ⭐ 为什么要判 DEVLOOP_CLEAN_CHECKOUT：
#     这几道守卫靠 `git status` 判断「工人改了什么」。
#     只有在某个提交的干净检出里，git 差异才**等于**工人的改动；
#     在本来就有未提交改动的工作区里，两者无法区分——
#     实测会产生误伤。所以那种情况必须 SKIP，⛔ 不许硬判。
#
if [ "${DEVLOOP_CLEAN_CHECKOUT:-0}" != "1" ]; then
  skip "改动守卫" "工作区有未提交改动，无法区分工人改动与在途改动——真实验收请用 --commit 走干净检出"
else
  # ── ⛔ 工人不得改测试来让自己过关——「闸自己放自己过」的等价物 ──
  #
  # ⚠️ 判据是「不许**改**已有断言」，**不是**「不许碰测试目录」。
  #    2026-07-29 实测：后者确实挡住了作弊，但把**合法写测试也一起挡了**——
  #    一单「加个函数并补两条测试」的正常活，工人干得完全正确却被判失败。
  #    按那种判据，工人永远无法为自己写的功能补测试：要么没测试，要么单单红。
  #
  #   · 改 / 删 / 改名已有测试 → 失败（削弱断言的唯一途径）
  #   · 新建 test_*.py         → 放行（新增断言只会更严）
  #   · 新建其它文件           → 失败。⛔ 专堵 `conftest.py`：一个 autouse
  #     fixture 就能架空整包已有测试，而它在 git status 里和正常新测试长得一样。
  #
  # ⛔ `-c core.quotepath=off` 不是可选项：git 默认把非 ASCII 路径转义并加引号，
  #    下面按 `\.py$` 结尾的匹配会全部对不上——非英文命名的新测试会被误判。
  #
  # 【按你的项目改】测试目录、以及「新增测试文件」长什么样（下面按 test_*.py）。
  dirty_tests=$(cd "$WORK" && git -c core.quotepath=off status --porcelain -- '<你的测试目录>/' 2>/dev/null | head -20)
  # ⛔ **守的东西不在，就不许说「未被改动」**（G-119，2026-08-04 实测）。
  #    「未被改动」在文件根本不存在时**恒真**——守卫会在最该报警的输入上静默变绿。
  #    ⭐ 那是第一种假绿：**守卫的目标不存在**。
  #    ⚠️ 每一道「查有没有被改动」的守卫，都要先问一句「它在不在」。
  if [ ! -d "$WORK/<你的测试目录>" ]; then
    void "测试守卫" "$WORK 下没有 <你的测试目录>/——⛔ 无可验之物，不是「未被改动」"
  elif [ -z "$dirty_tests" ]; then
    pass "测试守卫" "<你的测试目录>/ 未被改动"
  else
    changed=$(printf '%s\n' "$dirty_tests" | grep -Ev '^(\?\?|A ) ' | head -5)
    sneaky=$(printf '%s\n' "$dirty_tests" | grep -E '^(\?\?|A ) ' \
             | sed 's/^...//' | grep -Ev '(^|/)test_[^/]*\.py$' | head -5)
    if [ -n "$changed" ]; then
      bad "测试守卫" "工人**改动了已有测试**——改测试让自己过关不算通过：$(echo "$changed" | tr '\n' ' ')"
    elif [ -n "$sneaky" ]; then
      bad "测试守卫" "工人新建了非测试文件——conftest 之类能架空已有断言：$(echo "$sneaky" | tr '\n' ' ')"
    else
      n=$(printf '%s\n' "$dirty_tests" | grep -cE '^(\?\?|A ) ')
      pass "测试守卫" "已有测试一个字未改；新增 $n 个测试文件"
    fi
  fi

  # ⛔ 工人不得改自己的规矩（闸、规则摘要、宪法）
  #
  # ⚠️ 这一段要**同时覆盖两种项目状态**，否则守卫要么恒真要么恒假：
  #      · `.devloop/` 被 git 跟踪  → 用 git status 查它有没有被改
  #      · `.devloop/` 未被跟踪    → 干净检出里本就不该出现它
  #    本项目两种都栽过：先是恒 PASS（未跟踪时 status 永远为空），
  #    改成「存在即失败」后，又在已跟踪的项目上恒 FAIL。
  if git -C "$WORK" ls-files --error-unmatch .devloop >/dev/null 2>&1; then
    dirty_prot=$(cd "$WORK" && git status --porcelain -- '.devloop/' 2>/dev/null | head -3)
    if [ -n "$dirty_prot" ]; then
      bad "禁改清单" ".devloop/ 被改动——工人不得修改自己的规则与闸"
    else
      pass "禁改清单" ".devloop/ 已跟踪且未被改动"
    fi
  elif [ -e "$WORK/.devloop" ]; then
    bad "禁改清单" "工人在 worktree 里创建了 .devloop/ —— 该项目未跟踪它，它不该出现"
  else
    #  ⛔ **这一行以前写的是 `pass`，而那正是 G-68 立项时踩到的那条假绿**
    #     （2026-08-01 eco-ob 首跑：`禁改清单` 报 PASS，实际验了 0 条它冠名
    #     要保护的东西）。⚠️ 项目不跟踪 .devloop 时，闸与规则**根本不在仓内**，
    #     工人无从修改它——保护对象不存在，就不是「保护成功」。
    #  ⭐ 判 VOID 而不是 PASS：点名这道闸的计划会因此落退出码 2 交人，
    #     而不是拿到一个「验过了」的假象。
    void "禁改清单" "该项目未跟踪 .devloop/——受保护的规则与闸不在仓内，无可验之物"
  fi

  # ── 基线守卫（有基线数据的项目才需要）─────────────────────
  #
  # ⚠️ 这道守卫只能抓「工作区里的改动」。工人把改动**提交掉**，
  #    工作区就干净了，它就抓不到——那一半由**宪法的 base 锚定判据**补
  #    （见 .devloop/constitution.toml 的 [[protected_tree]]）。
  #    ⛔ 别以为有了这道就够了。
  #
  # ⛔ **中间那一支不许省**（G-119，2026-08-04 实测）：
  #    目标不存在时「未被改动」**恒真**，守卫会在最该报警的输入上静默变绿。
  #    实测：拿一个空目录跑 eco-ob 的闸，两道守卫都印「通过」。
  #    ⭐ 那是第一种假绿：**守卫的目标不存在**。
  #    ⚠️ 每一道「查有没有被改动」的守卫，都要先问一句「它在不在」。
  #
  # dirty_base=$(cd "$WORK" && git status --porcelain -- '<你的基线文件模式>' 2>/dev/null | head -5)
  # if [ -n "$dirty_base" ]; then
  #   bad "基线守卫" "基线数据被修改：$(echo "$dirty_base" | tr '\n' ' ')"
  # elif ! ls "$WORK"/<你的基线文件模式> >/dev/null 2>&1; then
  #   void "基线守卫" "$WORK 下一个基线文件都没有——⛔ 无可验之物，不是「未被改动」"
  # else
  #   pass "基线守卫" "<你的基线文件模式> 未被改动"
  # fi
fi


