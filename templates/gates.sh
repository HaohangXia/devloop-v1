TEST_TIMEOUT="${TEST_TIMEOUT:-<秒数>}"
if out=$(cd "$WORK" && timeout "$TEST_TIMEOUT" <你的测试命令> 2>&1); then
  pass "测试" "$(printf '%s' "$out" | tail -1)"
else
  rc=$?
  if [ $rc -eq 124 ]; then
    bad "测试" "超时（>${TEST_TIMEOUT}s）"
  else
    bad "测试" "$(printf '%s' "$out" | tail -3 | tr '\n' ' ')"
  fi
