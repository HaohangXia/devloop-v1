"""⛔ 新项目接入清单里，**验收动作不许绕开闸**。

## 这条是怎么来的（2026-08-16）

`SPEC.md` §6 的接入清单，2026-08-16 之前唯一的验证动作是：

> **验证**：派一个只读任务……确认能跑通、回执模型正确、禁令被遵守

⛔ **而只读单恰恰是唯一不建工位、不跑闸的那种**
（`cli.py`：`writes = args.tools != "readonly"`；闸只在 `if wt:` 里跑）。

⇒ **接入验收把唯一杀过人的东西整个绕开了，还要花订阅额度。**

⭐ 实测账单：靶子项目连败 4 单，其中 **3 单死在闸上**、不是死在作业上。
铁证是 2026-08-05 那一单：工人**一个文件都没动**，闸照样红
（`✗ M1 回归: 退出码 1，通过 37 失败 1`）。

⭐ 真正该做的那件事**不花一分额度、几秒出结果**：什么都不改，看闸绿不绿。

## ⛔ 为什么判据不能是「找个人照说明书走一遍」

那正是这个项目反复栽的那种判据 —— **文档会漂回去，而漂回去时没有任何东西会红**。
⚠️ 而且「照说明书走一遍」要花额度，⇒ 没人会天天走。

⭐ 所以判据落在**文本上但只认两件可证伪的事**：
① 清单里**出现**零改动跑闸那条命令；② 只读那一步**没被删掉**。

⚠️ 这仍是代用品（它守的是措辞，不是行为）。⭐ 更稳的收口是把这一步做成一个子命令，
说明书只引用命令名 —— 那样文案漂移就**不可能**改变行为。⛔ 未做，已记进 BACKLOG。
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
SPEC = REPO / "SPEC.md"


def _section() -> str:
    """取 `## 6. 新项目接入清单` 那一节的正文。"""
    src = SPEC.read_text(encoding="utf-8")
    m = re.search(r"^## 6\..*?接入清单.*?$(.*?)^## ", src, re.M | re.S)
    assert m, "⛔ `SPEC.md` 里找不到「## 6. …接入清单」那一节 —— 判据的目标不存在了"
    return m.group(1)


def test_接入清单里必须有零改动跑闸这一步() -> None:
    """⛔ 少了它，接入验收唯一的动作是只读单 —— 而只读单不跑闸。"""
    sec = _section()
    assert "devloop gates --project" in sec, (
        "⛔ 接入清单里没有「零改动跑一次闸」这一步。\n"
        "   ⇒ 唯一的验证动作会退回成只读单，⚠️ 而只读单**不建工位、不跑闸**\n"
        "   （`cli.py`：`writes = args.tools != \"readonly\"`）——\n"
        "   ⭐ 等于把唯一杀过人的东西整个绕开，还要花订阅额度。")
    assert "--commit HEAD" in sec, (
        "⛔ 那条命令没带 `--commit HEAD` —— 不带就验的是**工作区**，\n"
        "   ⚠️ 工作区可能有在途改动，验出来的绿说明不了「零改动时闸是绿的」。")


def test_退出码必须是0这句判据不许丢() -> None:
    """⛔ 只写「跑一次闸」不够 —— 得说清**什么算过**。

    ⚠️ 「判退出码是不是 0」在**闸内部**是最贵的错误写法（模板里列为第 4 条摆设写法），
    ⭐ 但在**接入绿检**这一步它恰恰是对的判据：这时工人零改动，
    退出码非 0 就说明闸测的不是工人。⛔ 两个场景别混。
    """
    sec = _section()
    assert re.search(r"退出码必须是\s*0", sec), (
        "⛔ 绿检那一步没写清判据。⭐ 原话该是「退出码必须是 0，FAIL 必须是 0 行」。")


def test_只读单那一步不许被删掉() -> None:
    """⛔ 别把只读那步「改成」绿检 —— 它核对的三样里有两样闸答不了。

    ⭐ 尤其「**回执模型正确**」：整份接入清单里**只有这一次**核对
    「工人真的跑在约定的模型上」。⚠️ 删了它，接错模型这件事在接入阶段一次都不会被发现。
    """
    sec = _section()
    assert "只读任务" in sec, (
        "⛔ 只读单那一步没了。⚠️ 它同时核对**能跑通 / 回执模型正确 / 禁令被遵守**，"
        "⭐ 而闸只答得了第一样。")
    assert "回执模型" in sec, (
        "⛔ 「回执模型正确」这句丢了 —— 那是整份清单里唯一一次核对"
        "「工人是不是真跑在约定的模型上」。")


def test_清单的步数与实际条目数对得上() -> None:
    """⛔ 标题写「三步」正文四条，是这份文档反复出过的那种自相矛盾。"""
    src = SPEC.read_text(encoding="utf-8")
    m = re.search(r"^## 6\.\s*新项目接入清单（(.)步）", src, re.M)
    assert m, "⛔ 「## 6. 新项目接入清单（N步）」这个标题形状变了"
    zh = "零一二三四五六七八九"
    claimed = zh.index(m.group(1))
    real = len(re.findall(r"^\d+\.\s", _section(), re.M))
    assert claimed == real, (
        f"⛔ 标题说 {m.group(1)} 步，正文实际 {real} 条。"
        f"⚠️ 同一份文档 §6 与「交付物」那节已经因为这种事互相矛盾过一次。")


def test_只读单确实不跑闸这个前提还成立() -> None:
    """⛔⛔ 这一条守的是**上面几条的前提**。

    ⚠️ 如果哪天只读单也跑闸了，上面那些断言就变成了在防一个不存在的问题
    —— 而它们仍会全绿（第①种假绿：守卫的目标不存在）。
    ⭐ 那时该做的是**回来改这份测试**，不是继续照着旧前提写文档。
    """
    src = (REPO / "devloop" / "cli.py").read_text(encoding="utf-8")
    assert 'writes = args.tools != "readonly"' in src, (
        "⛔ 「只读单不建工位」这个前提变了 —— 上面几条断言的理由需要重写。\n"
        "   ⭐ 先去核实：只读单现在跑闸吗？跑的话，接入清单第 4 步就不再是「绕开闸」了。")


@pytest.mark.parametrize("phrase", ["不建工位", "不跑闸"])
def test_接入清单要说清为什么只读单不够(phrase: str) -> None:
    """⛔ 只写「加一步」不写「为什么」，下一个人会把它当冗余删掉。

    ⚠️ 这份文档已经因为「删掉看起来冗余的东西」栽过 —— 理由必须和动作写在一起。
    """
    assert phrase in _section(), (
        f"⛔ 接入清单里没说清「{phrase}」—— 而那正是这一步存在的全部理由。")
